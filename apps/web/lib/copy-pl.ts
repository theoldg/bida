/**
 * Polish, filled in a section at a time with the owner. "???" is a line not yet
 * translated; the shape is `Copy`, so the compiler names anything English has
 * that this lacks. Shown only when /diag's Language says Polski.
 *
 * The owner's conventions: "ty", never "Pan/Pani", and capitalised as in a
 * letter: Ty, Twój, Ciebie, Ci. A name is never declined
 * (a member is whatever they typed): rephrase so it stands in the nominative,
 * "Usunąć: Ana?" rather than "Usunąć Anę?". A group's name stands beside the
 * word grupa, which takes the case: "Dołącz do grupy Wyjazd".
 *
 * The glossary, chosen by the owner: entry wpis · expense wydatek · income
 * wpływ · transfer przelew · balance saldo · share udział · receipt and bill
 * alike paragon · invite link "link z zaproszeniem", but the menu's button is
 * "Kopiuj link" · group grupa · history historia · people and members osoby ·
 * split podział, podzielić · scan skan, skanuj · amount kwota · currency waluta
 * · rate kurs · title tytuł · note notatka · date data. You owe "masz do
 * oddania", you're owed "należy Ci się". Undecided: any past tense that agrees
 * with a name. A verb may change with a count (`byCount`): rearranging a
 * sentence to dodge one reads worse.
 */
const rules = new Intl.PluralRules("pl");

/** A verb agrees with its count as the noun does: 1 czeka, 3 czekają, 5 czeka. */
function byCount(n: number, one: string, few: string, many: string): string {
  const form = rules.select(n);
  return form === "one" ? one : form === "few" ? few : many;
}

